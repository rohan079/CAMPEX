"""Phase 3 Creative Studio: ad copy variations and single-image ad artwork.

Copy is generated by the configured LLM, then checked deterministically:
* every number must come from the client's verified facts (no invented prices, sizes, dates or returns);
* risky real-estate claims (guaranteed/assured returns, approvals not in the facts, "best investment"...) are flagged.
Artwork is generated with OpenAI Images and is never treated as a factual claim: the prompt forbids text, prices
and logos in the image so that every claim stays in reviewable copy.
"""

from __future__ import annotations

import base64
import json
import logging
import re
from dataclasses import dataclass
from typing import Any

import httpx

from config import Settings
from services.llm_providers import LlmAdapter, ProviderUnavailable, parse_json
from services.performance_intelligence import allowed_numbers, check_grounding

logger = logging.getLogger(__name__)

CTAS = ["LEARN_MORE", "SIGN_UP", "CONTACT_US", "MESSAGE_PAGE", "BOOK_NOW", "GET_QUOTE", "APPLY_NOW"]

# Claims that need evidence a marketer must hold, or that are not allowed in property ads at all.
RISKY_PATTERNS: list[tuple[str, str]] = [
    (r"\bguarantee(d|s)?\b", "Guarantees are not allowed in property ads"),
    (r"\bassured (returns?|rental|income|appreciation)\b", "Assured returns are not allowed"),
    (r"\b(double|triple) your (money|investment)\b", "Return promises are not allowed"),
    (r"\b(risk[- ]free|no risk|100% safe)\b", "Risk-free claims are not allowed"),
    (r"\bbest investment\b", "Unverifiable superlative"),
    (r"\b(rera|dtcp|hmda|bmrda|cmda)[- ]?(approved|registered)\b", "Approval claims must match the verified facts"),
    (r"\b(ready to move|possession (in|by))\b", "Possession timing must match the verified facts"),
    (r"\b(lowest price|cheapest)\b", "Unverifiable superlative"),
]

COPY_SYSTEM = """You write Meta ad copy for Campex users (real-estate advertisers, freelancers and agencies).
Rules:
- Use ONLY facts from VERIFIED_FACTS and the BRIEF. Never invent prices, sizes, distances, approvals (RERA/DTCP/etc.),
  possession dates, amenities, discounts, rental yields or returns.
- Do not include any number that is not in VERIFIED_FACTS or the BRIEF.
- Never promise or guarantee returns, appreciation or outcomes. No "best investment", "risk-free" or similar.
- If a fact is missing, write around it (e.g. "Ask for the price list") instead of guessing.
- Match the requested language and brand tone. Keep headlines <= 40 characters and primary text <= 125 characters
  where possible.
Return ONLY a JSON object with keys:
"headlines" (exactly 5 strings), "primary_texts" (exactly 3 strings), "descriptions" (exactly 3 strings),
"cta_recommendations" (1-3 objects {"cta": one of %s, "reason": string}),
"concepts" (2-3 objects {"title": string, "visual": string, "angle": string}) where "visual" describes artwork
without any text, prices or logos in the image.""" % ", ".join(CTAS)


@dataclass
class ClaimCheck:
    unsupported_numbers: list[str]
    flagged_phrases: list[dict[str, str]]

    @property
    def clean(self) -> bool:
        return not self.unsupported_numbers and not self.flagged_phrases


def _texts(copy: dict[str, Any]) -> list[str]:
    out: list[str] = []
    for key in ("headlines", "primary_texts", "descriptions"):
        out.extend(str(v) for v in copy.get(key, []) if isinstance(v, (str, int, float)))
    return out


def check_claims(texts: list[str], facts: list[str], brief: dict[str, Any]) -> ClaimCheck:
    """Deterministic claim check over generated (or user-edited) copy."""
    allowed = allowed_numbers(facts, brief)
    unsupported: set[str] = set()
    flagged: list[dict[str, str]] = []
    facts_text = " ".join(facts).lower()
    for text in texts:
        unsupported.update(check_grounding(text, allowed).unsupported)
        lower = text.lower()
        for pattern, reason in RISKY_PATTERNS:
            match = re.search(pattern, lower)
            if not match:
                continue
            # An approval/possession phrase is fine when the verified facts state it.
            if ("approval" in reason.lower() or "possession" in reason.lower()) and match.group(0) in facts_text:
                continue
            flagged.append({"text": match.group(0), "reason": reason})
    unique = {(f["text"], f["reason"]): f for f in flagged}
    return ClaimCheck(sorted(unsupported), list(unique.values()))


def _clean_list(value: Any, n: int, max_len: int) -> list[str]:
    items = [str(v).strip()[:max_len] for v in value if isinstance(v, (str, int, float)) and str(v).strip()] \
        if isinstance(value, list) else []
    return items[:n]


class CreativeStudioService:
    def __init__(self, adapter: LlmAdapter):
        self._adapter = adapter

    async def generate_copy(self, brief: dict[str, Any], facts: list[str]) -> dict[str, Any]:
        user = ("VERIFIED_FACTS:\n" + json.dumps(facts, ensure_ascii=False)
                + "\n\nBRIEF:\n" + json.dumps(brief, ensure_ascii=False))
        copy, result = await self._complete(user)
        check = check_claims(_texts(copy), facts, brief)
        if not check.clean:
            retry = (user + "\n\nYour previous copy had problems. Numbers not in VERIFIED_FACTS: "
                     + (", ".join(check.unsupported_numbers) or "none") + ". Risky phrases: "
                     + (", ".join(f["text"] for f in check.flagged_phrases) or "none")
                     + ". Rewrite all variations without them.")
            copy, result = await self._complete(retry)
            check = check_claims(_texts(copy), facts, brief)
        ctas = []
        for item in copy.get("cta_recommendations", []) if isinstance(copy.get("cta_recommendations"), list) else []:
            if isinstance(item, dict) and item.get("cta") in CTAS:
                ctas.append({"cta": item["cta"], "reason": str(item.get("reason", ""))[:300]})
        concepts = []
        for item in copy.get("concepts", []) if isinstance(copy.get("concepts"), list) else []:
            if isinstance(item, dict):
                concepts.append({k: str(item.get(k, ""))[:600] for k in ("title", "visual", "angle")})
        return {
            "headlines": _clean_list(copy.get("headlines"), 5, 80),
            "primary_texts": _clean_list(copy.get("primary_texts"), 3, 1500),
            "descriptions": _clean_list(copy.get("descriptions"), 3, 255),
            "cta_recommendations": ctas[:3] or [{"cta": "LEARN_MORE", "reason": "Safe default for lead campaigns."}],
            "concepts": concepts[:3],
            "claim_check": {"unsupported_numbers": check.unsupported_numbers, "flagged_phrases": check.flagged_phrases},
            "provider": result.provider,
            "model": result.model,
        }

    async def _complete(self, user: str):
        result = await self._adapter.complete(COPY_SYSTEM, user, max_tokens=2000)
        return parse_json(result.text), result


ARTWORK_RULES = (" Advertising photograph or illustration only. Do not render any text, numbers, prices, dates, "
                 "logos, watermarks or badges in the image. Do not depict approvals, certificates or price tags.")


ASPECTS = ("1:1", "4:5", "9:16")


def image_size(model: str, default: str, aspect: str | None) -> str:
    """The provider size closest to the wanted aspect; Campex then crops/fits it to the exact ratio."""
    if not aspect or aspect == "1:1":
        return default
    if model.startswith("gpt-image"):
        return "1024x1536"
    if model == "dall-e-3":
        return "1024x1792"
    return default


def _composition(aspect: str | None) -> str:
    if aspect == "9:16":
        return " Vertical 9:16 full-screen composition for Stories and Reels: keep the subject centred, with calm space at the top and bottom."
    if aspect == "4:5":
        return " Vertical 4:5 feed composition with the subject centred."
    return ""


class ImageGenerationError(RuntimeError):
    """Image generation failed; the message is safe to show to users."""


async def generate_ad_image(settings: Settings, prompt: str, reference: tuple[bytes, str] | None = None,
                            transport: httpx.AsyncBaseTransport | None = None, aspect: str | None = None) -> dict[str, str]:
    """Returns {"mime_type", "data_base64", "prompt", "model"}. Never returns a temporary provider URL."""
    if not settings.ai_image_enabled:
        raise ImageGenerationError("Image generation is disabled on the server.")
    if not settings.campaign_ai_api_key:
        raise ImageGenerationError("Image generation is not configured (missing API key).")
    model = (settings.ai_image_model or "dall-e-3").strip()
    full_prompt = prompt.strip()[:3000] + _composition(aspect) + ARTWORK_RULES
    size = image_size(model, settings.ai_image_size, aspect)
    headers = {"Authorization": f"Bearer {settings.campaign_ai_api_key}"}
    base = settings.ai_base_url.rstrip("/")
    try:
        async with httpx.AsyncClient(timeout=settings.ai_image_timeout_seconds, transport=transport) as client:
            if reference is not None:
                if not model.startswith("gpt-image"):
                    raise ImageGenerationError("Reference images need a GPT Image model (set AI_IMAGE_MODEL=gpt-image-1).")
                data, mime = reference
                response = await client.post(
                    f"{base}/images/edits", headers=headers,
                    data={"model": model, "prompt": full_prompt, "size": size, "n": "1"},
                    files={"image": ("reference." + (mime.split("/")[-1] or "png"), data, mime)},
                )
            else:
                payload: dict[str, Any] = {"model": model, "prompt": full_prompt, "size": size, "n": 1}
                if model.startswith("dall-e"):
                    payload["response_format"] = "b64_json"
                response = await client.post(f"{base}/images/generations", headers=headers, json=payload)
            if response.is_error:
                logger.warning("Creative image generation failed (HTTP %s)", response.status_code)
                detail = "Image generation failed."
                try:
                    err = response.json().get("error")
                    if isinstance(err, dict) and isinstance(err.get("message"), str):
                        detail = err["message"][:300]
                except ValueError:
                    pass
                raise ImageGenerationError(detail)
            body = response.json()
            first = body.get("data", [{}])[0] if isinstance(body, dict) and body.get("data") else {}
            b64 = first.get("b64_json") if isinstance(first, dict) else None
            if not b64 and isinstance(first, dict) and str(first.get("url", "")).startswith("https://"):
                # Download immediately: provider URLs expire and must never be stored as the creative reference.
                downloaded = await client.get(first["url"])
                if downloaded.is_error or not downloaded.content:
                    raise ImageGenerationError("Could not download the generated image.")
                b64 = base64.b64encode(downloaded.content).decode("ascii")
    except httpx.HTTPError as exc:
        logger.warning("Creative image request failed (%s)", type(exc).__name__)
        raise ImageGenerationError("Image generation endpoint could not be reached.") from exc
    except ValueError as exc:
        raise ImageGenerationError("Image generation returned an unreadable response.") from exc
    if not isinstance(b64, str) or not b64.strip():
        raise ImageGenerationError("Image generation returned no image.")
    return {"mime_type": "image/png", "data_base64": b64.strip(), "prompt": full_prompt, "model": model}


